"""Renders the measured score and keeps the audit document in step with it.

Rule V-01 requires every quantitative claim to carry the command that produced it,
so the generated block embeds its own command and `--check` exits non-zero the moment
the document drifts from measurement -- the contract `scripts/countTests.py` already
uses for test counts. Both are run by hand; this repository has no CI.
"""

import sys
from typing import List, Optional

from .auditTargets import blockEndMarker, blockStartMarker, documentedFilePaths, meshRoot
from .mutantRunner import ModuleResult


def renderScoreBlock(results: List[ModuleResult]) -> str:
    """Builds the generated block: the scores, then every surviving mutant."""
    lines = [
        blockStartMarker,
        "<!-- Generated by scripts/mutationScore.py -- do not edit by hand. -->",
        "",
    ]
    lines.extend(_renderScoreTable(results))
    lines.extend(_renderSurvivors(results))
    lines.extend(_renderUncovered(results))
    lines.extend(["", blockEndMarker])
    return "\n".join(lines)


def _renderScoreTable(results: List[ModuleResult]) -> List[str]:
    """The per-module score table, worst first."""
    totalKilled = sum(result.killedCount for result in results)
    totalScored = sum(result.scoredCount for result in results)
    totalScore = (100.0 * totalKilled / totalScored) if totalScored else 0.0

    lines = ["| Module | Mutants | Killed | Survived | Score |", "|---|---:|---:|---:|---:|"]
    lines.extend(
        f"| `{result.modulePath}` | {result.scoredCount} | {result.killedCount} "
        f"| {len(result.survivors)} | {result.scorePercent:.1f}% |"
        for result in sorted(results, key=lambda item: item.scorePercent)
    )
    lines.extend([
        f"| **All {len(results)} modules** | **{totalScored}** | **{totalKilled}** "
        f"| **{totalScored - totalKilled}** | **{totalScore:.1f}%** |",
        "",
        "Produced by `python scripts/mutationScore.py`.",
    ])
    lines.extend(_renderDegenerateKillNote(results))
    return lines


def _renderDegenerateKillNote(results: List[ModuleResult]) -> List[str]:
    """Separates out the kills that no assertion earned.

    A mutant that leaves the module un-importable, or that hangs the suite, is
    caught by any test at all rather than by a test that pins the behaviour. Those
    kills count -- the suite does go red -- but they flatter the score as a measure of
    assertion strength, so the reader is told how many there were and can subtract.
    """
    importKills = sum(result.collectionErrorCount for result in results)
    timeoutKills = sum(result.timeoutCount for result in results)
    if not importKills and not timeoutKills:
        return []
    return [
        "",
        f"Of the killed mutants, {importKills} were caught by the module failing to "
        f"import and {timeoutKills} by the suite hanging, rather than by an assertion "
        "objecting to a value. Those kills are real but degenerate: any test at all "
        "would have caught them.",
    ]


def _renderSurvivors(results: List[ModuleResult]) -> List[str]:
    """Every mutant the suite accepted, which is the evidence the score summarises."""
    lines = [
        "",
        "### Surviving mutants",
        "",
        "Each line is a change to the source that the entire suite accepts in silence.",
    ]
    survivingResults = [result for result in results if result.survivors]
    if not survivingResults:
        lines.extend(["", "None: every mutant was caught."])
        return lines

    for result in sorted(survivingResults, key=lambda item: item.modulePath):
        lines.extend(["", f"**`{result.modulePath}`**", "", "```"])
        lines.extend(
            f"L{mutant.lineNumber:<4} [{mutant.operatorName}]  "
            f"{mutant.beforeText}   ->   {mutant.afterText}"
            for mutant in result.survivors
        )
        lines.append("```")
    return lines


def _renderUncovered(results: List[ModuleResult]) -> List[str]:
    """Sites no test reaches at all, which the score cannot speak for."""
    uncovered = [
        (result.modulePath, mutant)
        for result in results
        for mutant in result.uncoveredMutants
    ]
    if not uncovered:
        return []
    lines = ["", "### Sites no test reaches", "", "```"]
    lines.extend(f"{modulePath}:{mutant.lineNumber}  {mutant.beforeText}" for modulePath, mutant in uncovered)
    lines.append("```")
    return lines


# --- Document synchronisation ------------------------------------------------


def extractBlock(text: str) -> Optional[str]:
    """Returns the generated block from a document, or None when it has none."""
    startIndex = text.find(blockStartMarker)
    endIndex = text.find(blockEndMarker)
    if startIndex == -1 or endIndex == -1:
        return None
    return text[startIndex : endIndex + len(blockEndMarker)]


def writeBlockToDocuments(renderedBlock: str) -> int:
    """Replaces the generated block in every documented file."""
    for documentPath in documentedFilePaths:
        if not documentPath.exists():
            print(f"ERROR: {documentPath} does not exist", file=sys.stderr)
            return 1
        text = documentPath.read_text(encoding="utf-8")
        existingBlock = extractBlock(text)
        if existingBlock is None:
            print(f"ERROR: {documentPath} has no {blockStartMarker} block", file=sys.stderr)
            return 1
        documentPath.write_text(text.replace(existingBlock, renderedBlock), encoding="utf-8")
        print(f"updated {documentPath.relative_to(meshRoot)}")
    return 0


def checkBlockInDocuments(renderedBlock: str) -> int:
    """Fails when a documented score no longer matches measurement."""
    hasDrifted = False
    for documentPath in documentedFilePaths:
        existingBlock = extractBlock(documentPath.read_text(encoding="utf-8"))
        if existingBlock is None or existingBlock.strip() != renderedBlock.strip():
            print(f"DRIFT: {documentPath} disagrees with measurement", file=sys.stderr)
            hasDrifted = True
    if hasDrifted:
        print("\nRun `python scripts/mutationScore.py --write` to resynchronise.", file=sys.stderr)
        return 1
    print("OK: the documented mutation score matches measurement.")
    return 0
